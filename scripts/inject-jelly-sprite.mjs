#!/usr/bin/env node
/**
 * Factor Font Awesome jelly-regular SVGs into the repo:
 * - demo/icons/jelly/{id}.svg  (subset)
 * - demo/icons/sprite.svg
 * - symbols injected into demo/index.html
 * - packages/react/src/jelly-icons.tsx (alert tones)
 *
 * Source (not committed): ../fontawesome-pro-plus-7.3.0-web/svgs/jelly-regular
 * Override with SG_JELLY_DIR.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jelly =
  process.env.SG_JELLY_DIR ||
  join(root, '..', 'fontawesome-pro-plus-7.3.0-web', 'svgs', 'jelly-regular');

/** demo Icon name → FA jelly file (sans .svg) */
const map = {
  search: 'magnifying-glass',
  mic: 'microphone',
  menu: 'bars',
  heart: 'heart',
  plus: 'plus',
  check: 'check',
  copy: 'clone',
  sun: 'sun',
  moon: 'moon',
  home: 'house',
  explore: 'compass',
  bookmark: 'bookmark',
  user: 'user',
  info: 'circle-info',
  warning: 'triangle-exclamation',
  success: 'circle-check',
  error: 'circle-xmark',
  chevron: 'angle-down',
  play: 'play',
  image: 'image',
};

const alertIds = ['info', 'warning', 'success', 'error'];

function pathOf(file) {
  const c = readFileSync(join(jelly, `${file}.svg`), 'utf8');
  const m = c.match(/\sd="([^"]+)"/);
  if (!m) throw new Error(`no path in ${file}`);
  return m[1];
}

if (!existsSync(jelly)) {
  console.error('missing jelly dir:', jelly);
  process.exit(1);
}

const outDir = join(root, 'demo', 'icons', 'jelly');
mkdirSync(outDir, { recursive: true });

const paths = {};
for (const [id, file] of Object.entries(map)) {
  const src = join(jelly, `${file}.svg`);
  if (!existsSync(src)) throw new Error(`missing ${file}`);
  paths[id] = pathOf(file);
  copyFileSync(src, join(outDir, `${id}.svg`));
}

const symbols = Object.entries(paths)
  .map(
    ([id, d]) =>
      `  <symbol id="i-${id}" viewBox="0 0 560 560"><path fill="currentColor" d="${d}"/></symbol>`,
  )
  .join('\n');

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true" focusable="false">
${symbols}
</svg>
`;
writeFileSync(join(root, 'demo', 'icons', 'sprite.svg'), sprite);

const htmlPath = join(root, 'demo', 'index.html');
let html = readFileSync(htmlPath, 'utf8');
const re =
  /(<svg width="0" height="0"[\s\S]*?<defs>[\s\S]*?<\/filter>)[\s\S]*?(<\/defs>\s*<\/svg>)/;
if (!re.test(html)) {
  console.error('sprite block not found in demo/index.html');
  process.exit(1);
}
const inlineSymbols = Object.entries(paths)
  .map(
    ([id, d]) =>
      `    <symbol id="i-${id}" viewBox="0 0 560 560"><path fill="currentColor" d="${d}"/></symbol>`,
  )
  .join('\n');
html = html.replace(re, (_, head, tail) => `${head}\n${inlineSymbols}\n  ${tail}`);
writeFileSync(htmlPath, html);

const reactIcons = `/* Auto-generated by scripts/inject-jelly-sprite.mjs — FA jelly-regular subset */
import type { ReactNode } from 'react';

function jelly(d: string, size = 22): ReactNode {
  return (
    <svg viewBox="0 0 560 560" width={size} height={size} aria-hidden>
      <path fill="currentColor" d={d} />
    </svg>
  );
}

const PATH = {
${alertIds.map((id) => `  ${id}: '${paths[id]}',`).join('\n')}
} as const;

/** Alert tone → Jelly icon (circle-info / triangle-exclamation / circle-check / circle-xmark) */
export const JELLY_ALERT_ICONS: Record<string, ReactNode> = {
  info: jelly(PATH.info),
  warning: jelly(PATH.warning),
  success: jelly(PATH.success),
  danger: jelly(PATH.error),
  error: jelly(PATH.error),
};
`;
writeFileSync(join(root, 'packages', 'react', 'src', 'jelly-icons.tsx'), reactIcons);

console.log(
  `inject-jelly: ${Object.keys(map).length} icons → demo/icons/jelly + sprite + index.html + react`,
);
