#!/usr/bin/env node
/**
 * Factor ALL Font Awesome jelly-regular SVGs into the repo (365):
 * - demo/icons/jelly/{fa-name}.svg
 * - demo/icons/sprite.svg  (symbols #i-{fa-name})
 * - demo/icons/aliases.js  (SG_ICON_ALIAS + SG_ICON_CATALOG)
 * - packages/react/src/jelly-icons.tsx (alert tones)
 * - strips inline icon symbols from demo/index.html (sprite via <use>)
 *
 * Source: ../fontawesome-pro-plus-7.3.0-web/svgs/jelly-regular
 * Override with SG_JELLY_DIR.
 */
import {
  readFileSync,
  writeFileSync,
  existsSync,
  mkdirSync,
  copyFileSync,
  readdirSync,
  rmSync,
} from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jelly =
  process.env.SG_JELLY_DIR ||
  join(root, '..', 'fontawesome-pro-plus-7.3.0-web', 'svgs', 'jelly-regular');

/** Short demo names → FA jelly id (identity aliases omitted) */
const ALIAS = {
  search: 'magnifying-glass',
  mic: 'microphone',
  menu: 'bars',
  copy: 'clone',
  home: 'house',
  explore: 'compass',
  info: 'circle-info',
  warning: 'triangle-exclamation',
  success: 'circle-check',
  error: 'circle-xmark',
  chevron: 'angle-down',
};

const ALERT_FA = {
  info: 'circle-info',
  warning: 'triangle-exclamation',
  success: 'circle-check',
  error: 'circle-xmark',
};

function pathOf(filePath) {
  const c = readFileSync(filePath, 'utf8');
  const m = c.match(/\sd="([^"]+)"/);
  if (!m) throw new Error(`no path in ${filePath}`);
  return m[1];
}

if (!existsSync(jelly)) {
  console.error('missing jelly dir:', jelly);
  process.exit(1);
}

const files = readdirSync(jelly)
  .filter((f) => f.endsWith('.svg'))
  .sort();
if (files.length !== 365) {
  console.warn(`expected 365 jelly SVGs, found ${files.length}`);
}

const outDir = join(root, 'demo', 'icons', 'jelly');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const names = [];
const symbols = [];
for (const file of files) {
  const id = basename(file, '.svg');
  const src = join(jelly, file);
  copyFileSync(src, join(outDir, file));
  const d = pathOf(src);
  names.push(id);
  symbols.push(
    `  <symbol id="i-${id}" viewBox="0 0 560 560"><path fill="currentColor" d="${d}"/></symbol>`,
  );
}

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true" focusable="false">
${symbols.join('\n')}
</svg>
`;
writeFileSync(join(root, 'demo', 'icons', 'sprite.svg'), sprite);
try {
  rmSync(join(root, 'demo', 'icons', 'catalog.json'), { force: true });
} catch {
  /* legacy file */
}

/* Strip inline icon symbols from index.html — keep filter only */
const htmlPath = join(root, 'demo', 'index.html');
let html = readFileSync(htmlPath, 'utf8');
const re =
  /(<svg width="0" height="0"[\s\S]*?<defs>[\s\S]*?<\/filter>)[\s\S]*?(<\/defs>\s*<\/svg>)/;
if (!re.test(html)) {
  console.error('sprite block not found in demo/index.html');
  process.exit(1);
}
html = html.replace(re, (_, head, tail) => `${head}\n  ${tail}`);
writeFileSync(htmlPath, html);

const reactIcons = `/* Auto-generated by scripts/inject-jelly-sprite.mjs — FA jelly-regular */
import type { ReactNode } from 'react';

function jelly(d: string, size = 22): ReactNode {
  return (
    <svg viewBox="0 0 560 560" width={size} height={size} aria-hidden>
      <path fill="currentColor" d={d} />
    </svg>
  );
}

const PATH = {
${Object.entries(ALERT_FA)
  .map(([k, fa]) => `  ${k}: '${pathOf(join(jelly, fa + '.svg'))}',`)
  .join('\n')}
} as const;

/** Alert tone → Jelly icon */
export const JELLY_ALERT_ICONS: Record<string, ReactNode> = {
  info: jelly(PATH.info),
  warning: jelly(PATH.warning),
  success: jelly(PATH.success),
  danger: jelly(PATH.error),
  error: jelly(PATH.error),
};
`;
writeFileSync(join(root, 'packages', 'react', 'src', 'jelly-icons.tsx'), reactIcons);

/* Expose aliases for the demo Icon helper */
writeFileSync(
  join(root, 'demo', 'icons', 'aliases.js'),
  `/* Auto-generated by scripts/inject-jelly-sprite.mjs */
window.SG_ICON_ALIAS = ${JSON.stringify(ALIAS, null, 2)};
window.SG_ICON_CATALOG = ${JSON.stringify(names)};
`,
);

console.log(`inject-jelly: ${names.length} icons → demo/icons/jelly + sprite + aliases.js`);
