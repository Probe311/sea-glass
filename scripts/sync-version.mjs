/**
 * Sync displayed version with package.json (repo / release source of truth)
 * and React with the installed dependency.
 *
 * Writes demo/version.js, pins esm.sh React in demo/index.html,
 * and updates legacy/ footer strings (snapshot kept in sync).
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = require(join(root, 'package.json'));

function resolveReact() {
  for (const rel of [
    'node_modules/react/package.json',
    'packages/react/node_modules/react/package.json',
  ]) {
    try {
      return require(join(root, rel)).version;
    } catch {
      /* continue */
    }
  }
  const raw = require(join(root, 'packages/react/package.json')).devDependencies?.react ?? '19.3.0';
  return (
    String(raw)
      .replace(/^[^\d]*/, '')
      .split(/\s/)[0] || '19.3.0'
  );
}

const version = pkg.version;
const react = resolveReact();
const line = `${version} · React ${react}`;

writeFileSync(
  join(root, 'demo/version.js'),
  `/* Generated by scripts/sync-version.mjs — do not edit. */
window.SG_META = ${JSON.stringify({ version, react, line }, null, 2)};
`,
);

function patch(file, replacers) {
  let src = readFileSync(file, 'utf8');
  const before = src;
  for (const [re, to] of replacers) src = src.replace(re, to);
  if (src !== before) {
    writeFileSync(file, src);
    console.log(`patched ${file}`);
  }
}

patch(join(root, 'demo/index.html'), [
  [
    /const v = window\.SG_META\?\.react \|\| '[^']+'/,
    `const v = window.SG_META?.react || '${react}'`,
  ],
]);

const legacyReplacers = [
  [/h\('div', \{ className: 'foot' \}, '[^']*'\)/g, `h('div', { className: 'foot' }, '${line}')`],
  [
    /h\('span', \{ className: 'label' \}, '[^']*'\)/g,
    `h('span', { className: 'label' }, 'Design system · ${version}')`,
  ],
  [
    /h\('span', null, 'Sea Glass(?: Design System)? · [^']*'\)/g,
    `h('span', null, 'Sea Glass · ${version}')`,
  ],
];

for (const rel of ['legacy/sec-a.js', 'legacy/sec-c.js']) {
  patch(join(root, rel), legacyReplacers);
}

console.log(`SG_META → ${line}`);
